function makeEvidence(seed: CandidateSeed, index: number): EvidenceDatum[] {
  const primaryStatus = seed.evidenceStatus ?? "verified";

  return [
    {
      id: `${seed.parcelId}-identity`,
      label: "Parcel identity",
      value: seed.parcelId,
      status: primaryStatus === "conflicting" ? "conflicting" : "verified",
      source: `${seed.county} County parcel records`,
      observedAt: "2026-08-11T15:20:00-05:00",
      detail: "Synthetic source observation for interface validation.",
    },
    {
      id: `${seed.parcelId}-value`,
      label: "Value range",
      value: `${formatMoneyCompact(seed.low)}–${formatMoneyCompact(seed.high)}`,
      status: "estimated",
      source: `Comparable set CTX-${String(index + 1).padStart(3, "0")}`,
      observedAt: "2026-08-10T09:00:00-05:00",
      detail: "Scenario estimate; not an appraisal or offer recommendation.",
    },
    {
      id: `${seed.parcelId}-owner`,
      label: "Ownership role",
      value: primaryStatus === "unknown" ? "Unresolved" : "Record owner observed",
      status: primaryStatus === "stale" || primaryStatus === "unknown" ? primaryStatus : "verified",
      source: "Recorded deed and assessor observations",
      observedAt: primaryStatus === "stale" ? "2025-10-04T12:00:00-05:00" : "2026-08-09T12:00:00-05:00",
      detail: "A record-owner observation is not contact-point or negotiation authority.",
    },
    {
      id: `${seed.parcelId}-geo`,
      label: "Risk overlays",
      value: index % 3 === 0 ? "Review required" : "Screen complete",
      status: index % 3 === 0 ? "estimated" : "verified",
      source: "Versioned public GIS layers",
      observedAt: "2026-08-08T18:30:00-05:00",
      detail: "Desktop screening requires site and professional verification.",
    },
  ];
}

function makeRisks(seed: CandidateSeed, index: number): CandidateRisk[] {
  return [
    {
      id: `${seed.parcelId}-risk-primary`,
      label: seed.riskLabel,
      detail: seed.riskDetail,
      severity: index % 5 === 3 ? "critical" : "elevated",
    },
    {
      id: `${seed.parcelId}-risk-title`,
      label: "Title review not complete",
      detail: "No title, survey, legal, or environmental conclusion is represented.",
      severity: "watch",
    },
    {
      id: `${seed.parcelId}-risk-source`,
      label: index % 4 === 0 ? "Source freshness watch" : "Field verification pending",
      detail: "The ranking remains subject to due diligence and source refreshes.",
      severity: "watch",
    },
  ];
}

function makeCandidate(seed: CandidateSeed, index: number): CandidateSummary {
  const evidence = makeEvidence(seed, index);
  const identityReady = !evidence.some((item) =>
    ["unknown", "conflicting", "stale"].includes(item.status),
  );

  return {
    id: `candidate-${String(index + 1).padStart(2, "0")}`,
    rank: index + 1,
    previousRank: seed.previousRank,
    name: seed.name,
    locality: seed.locality,
    county: seed.county,
    parcelId: seed.parcelId,
    acreage: seed.acreage,
    strategy: seed.strategy,
    queueState: seed.queueState,
    overallScore: seed.score,
    confidence: seed.confidence,
    valueRange: { low: seed.low, high: seed.high },
    likelyBasis: seed.basis,
    thesis: seed.thesis,
    nextAction: seed.nextAction,
    newSinceLastReview: seed.previousRank === null,
    materialChange: seed.change ?? null,
    risks: makeRisks(seed, index),
    evidence,
    outreachGate: {
      status: "blocked",
      reviewedChecks: identityReady ? 2 : 1,
      totalChecks: 5,
      blockers: [
        ...(identityReady ? [] : ["Responsible-party identity needs review"]),
        "No approved contact-point source",
        "Texas acquisition policy is not activated",
        "All outbound channels are disabled",
      ],
    },
  };
}

